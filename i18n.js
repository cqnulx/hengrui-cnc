export function translateInterface(language, key, fallback = key) {
  if (language === 'zh') return key || fallback;
  const index = languages[language]?.index;
  const lookup = text => Object.hasOwn(interfaceTranslations, text) ? interfaceTranslations[text][index] : undefined;
  return lookup(key) ?? lookup(fallback) ?? fallback;
}
